#!/usr/bin/env node
/**
 * Sync Hara design tokens from the shared design source into this repository.
 * Zero dependencies. The token files are generated: never edit them by hand, run this script instead.
 *
 *   node scripts/sync-design-tokens.mjs --from <design-source>/dist   copy the tokens and update DESIGN.md
 *   node scripts/sync-design-tokens.mjs --check [--from <dist>]        verify only (the test runs this)
 *
 * The source can also be given with HARA_DESIGN_DIST. DESIGN.md keeps a machine-readable block between the
 * hara-design-sync markers: version, sourceSha, source commit and the sha256 of every generated file.
 *
 * --check always verifies the recorded hashes (line endings are normalized to LF first, so a CRLF checkout
 * on Windows is not a hand edit). When the design source is available and is at the recorded sourceSha,
 * it also regenerates the tokens from the source and compares them byte for byte, which catches a file
 * and its recorded hash being edited together.
 *
 * Template: this file is identical in every repository except for the FILES line. Change the template in
 * the design source and copy it to every repository.
 */
import { createHash } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

/** [file in the design source dist/, path in this repository] */
export const FILES = [["hara-tokens.cli.ts", "src/tui/hara-tokens.generated.ts"]]

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const DESIGN = join(ROOT, 'DESIGN.md')
const START = '<!-- hara-design-sync:start (generated by scripts/sync-design-tokens.mjs — do not edit) -->'
const END = '<!-- hara-design-sync:end -->'
const lf = text => text.replace(/\r\n/g, '\n')
const sha256 = text => createHash('sha256').update(lf(text)).digest('hex')
const read = path => lf(readFileSync(path, 'utf8'))
const headerOf = text => {
  const m = text.match(/version (\d+\.\d+\.\d+) · sourceSha ([0-9a-f]{64})/) ?? text.match(/"version": "(\d+\.\d+\.\d+)",\s*"sourceSha": "([0-9a-f]{64})"/)
  return m ? { version: m[1], sourceSha: m[2] } : null
}
const sourceDir = argv => { const k = argv.indexOf('--from'); return k > 0 ? resolve(argv[k + 1]) : process.env.HARA_DESIGN_DIST ? resolve(process.env.HARA_DESIGN_DIST) : null }

export function readBlock(designText = read(DESIGN)) {
  const text = lf(designText), i = text.indexOf(START), j = text.indexOf(END)
  if (i < 0 || j < i) return null
  const body = text.slice(i + START.length, j)
  const field = k => body.match(new RegExp(`^- ${k}: \`([^\`]+)\``, 'm'))?.[1]
  const files = Object.fromEntries([...body.matchAll(/^\| `([^`]+)` \| `([0-9a-f]{64})` \|$/gm)].map(m => [m[1], m[2]]))
  return { version: field('version'), sourceSha: field('sourceSha'), commit: field('source commit'), files }
}

/** Regenerate from the design source (dist/../build_tokens.mjs + DESIGN.md). Returns null when the source is unavailable. */
async function regenerate(dist) {
  const src = dist && resolve(dist, '..'), gen = src && join(src, 'build_tokens.mjs'), design = src && join(src, 'DESIGN.md')
  if (!gen || !existsSync(gen) || !existsSync(design)) return null
  const { build } = await import(pathToFileURL(gen).href)
  return build(read(design))
}

/** Returns a list of problems; empty means the repository matches what DESIGN.md records (and the source, when given). */
export async function verify({ from = sourceDir(process.argv) } = {}) {
  const problems = [], block = readBlock()
  if (!block) return { problems: ['DESIGN.md has no hara-design-sync block'], regenerated: false }
  for (const [, target] of FILES) {
    const p = join(ROOT, target)
    if (!existsSync(p)) { problems.push(`${target} is missing`); continue }
    const text = read(p), head = headerOf(text)
    if (block.files[target] !== sha256(text)) problems.push(`${target} differs from the recorded sha256 (edited by hand? re-run the sync)`)
    if (!head || head.version !== block.version || head.sourceSha !== block.sourceSha) problems.push(`${target} header does not match DESIGN.md (${block.version})`)
  }
  for (const recorded of Object.keys(block.files)) if (!FILES.some(([, t]) => t === recorded)) problems.push(`DESIGN.md records unknown file ${recorded}`)
  let regenerated = false
  const out = await regenerate(from)
  if (out && out.sourceSha === block.sourceSha) {
    regenerated = true
    for (const [name, target] of FILES) {
      const p = join(ROOT, target)
      if (existsSync(p) && read(p) !== out.files[name]) problems.push(`${target} differs from the tokens regenerated from the design source`)
    }
  } else if (out) problems.push(`the design source is at ${out.version} (${out.sourceSha.slice(0, 12)}), this repository records ${block.version} (${block.sourceSha.slice(0, 12)}): run the sync`)
  return { problems, regenerated }
}

function sync(dist) {
  const meta = JSON.parse(read(join(dist, 'hara-tokens.json')))
  let commit = 'unknown'
  try { commit = execFileSync('git', ['-C', dist, 'log', '-1', '--format=%h', '--', '.'], { encoding: 'utf8' }).trim() || 'unknown' } catch { /* not a git checkout */ }
  const rows = []
  for (const [src, target] of FILES) {
    const text = read(join(dist, src)), head = headerOf(text)
    if (!head || head.sourceSha !== meta.sourceSha) throw new Error(`${src} is not from the same build as hara-tokens.json`)
    mkdirSync(dirname(join(ROOT, target)), { recursive: true })
    writeFileSync(join(ROOT, target), text)
    rows.push(`| \`${target}\` | \`${sha256(text)}\` |`)
  }
  const block = `${START}\n- version: \`${meta.version}\`\n- sourceSha: \`${meta.sourceSha}\`\n- source commit: \`${commit}\`\n\n| file | sha256 |\n|---|---|\n${rows.join('\n')}\n${END}`
  const design = read(DESIGN), i = design.indexOf(START), j = design.indexOf(END)
  if (i < 0 || j < i) throw new Error('DESIGN.md has no hara-design-sync markers')
  writeFileSync(DESIGN, design.slice(0, i) + block + design.slice(j + END.length))
  console.log(`synced Hara tokens ${meta.version} (${meta.sourceSha.slice(0, 12)}, source ${commit}) → ${FILES.map(([, t]) => t).join(', ')}`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const { problems, regenerated } = await verify()
    if (problems.length) { console.error(problems.join('\n')); process.exit(1) }
    console.log(`Hara tokens in sync (${readBlock().version})${regenerated ? ', regenerated from the design source and identical' : '; design source not given, hashes only'}`)
  } else {
    const dist = sourceDir(process.argv)
    if (!dist) { console.error('give the design source dist/ with --from <dir> or HARA_DESIGN_DIST'); process.exit(2) }
    sync(dist)
  }
}
