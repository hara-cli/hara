#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';

const root = fileURLToPath(new URL('..', import.meta.url));
const localesRoot = path.join(root, 'src/locales');
const generatedJson = path.join(localesRoot, 'zh-Hant/core-intents.generated.json');
const generatedTs = path.join(root, 'src/agent/core-intents.generated.ts');
const openccVersion = '1.3.1';
const configurations = ['s2twp.json', 's2tw.json', 's2t.json'];
const hash = value => createHash('sha256').update(value).digest('hex');
const json = value => JSON.stringify(value, null, 2) + '\n';
const mode = process.argv[2];
if (process.argv.length !== 3 || !['--generate', '--check', '--verify'].includes(mode)) {
  throw Error('Usage: node scripts/generate-core-intents.mjs --generate|--check|--verify');
}

const sources = {}, sourceHashes = {};
for (const dir of fs.readdirSync(localesRoot).sort()) {
  const file = path.join(localesRoot, dir, 'core-intents.json');
  if (!fs.existsSync(file)) continue;
  if (!/^[a-z]{2,3}(?:-[A-Za-z0-9]{2,8})*$/.test(dir) || dir === 'zh-Hant') throw Error('Invalid or generated source locale: ' + dir);
  const bytes = fs.readFileSync(file), value = JSON.parse(bytes);
  if (value.schemaVersion !== 1 || value.locale !== dir) throw Error('Invalid intent locale schema: ' + dir);
  sources[dir] = value.patterns;
  sourceHashes[dir] = hash(bytes);
}
if (!sources.en || !sources['zh-Hans']) throw Error('English and Simplified Chinese intent sources are required');
const keys = Object.keys(sources.en);
function validatePatterns(patterns, locale) {
  if (!patterns || JSON.stringify(Object.keys(patterns)) !== JSON.stringify(keys)) throw Error('Intent category coverage/order differs: ' + locale);
  for (const key of keys) {
    if (!Array.isArray(patterns[key]) || patterns[key].length < 1 || patterns[key].length > 8) throw Error('Invalid intent variants: ' + locale + '/' + key);
    for (const source of patterns[key]) {
      if (typeof source !== 'string' || !source || source.length > 8192 || /[\r\n\0]/u.test(source)) throw Error('Invalid intent pattern: ' + locale + '/' + key);
      new RegExp(source, 'iu');
    }
  }
}
for (const [locale, patterns] of Object.entries(sources)) validatePatterns(patterns, locale);

const correctionsBytes = fs.readFileSync(path.join(localesRoot, 'zh-Hant/core-intents.corrections.json'));
const corrections = JSON.parse(correctionsBytes);
const reviewedCorrectionsSha256 = hash(correctionsBytes);
const lexemes = [...new Set(Object.values(sources['zh-Hans']).flatMap(patterns => patterns.flatMap(source => source.match(/\p{Script=Han}+/gu) || [])))];
if (corrections.schemaVersion !== 1 || corrections.locale !== 'zh-Hant' || !corrections.corrections) throw Error('Invalid reviewed intent corrections');
for (const [term, configs] of Object.entries(corrections.corrections)) {
  if (!lexemes.includes(term)) throw Error('Correction does not refer to a current source term: ' + term);
  for (const [config, value] of Object.entries(configs)) {
    if (!configurations.includes(config) || !value.expected || !value.replacement || !value.reason || !/^\p{Script=Han}+$/u.test(value.replacement)) throw Error('Invalid reviewed correction: ' + term);
  }
}
function patternsFromLexemes(convertedLexemes) {
  if (!convertedLexemes || JSON.stringify(Object.keys(convertedLexemes)) !== JSON.stringify(lexemes)) throw Error('Generated Han lexeme coverage differs');
  const variants = {};
  for (const term of lexemes) {
    variants[term] = [];
    for (const config of configurations) {
      const raw = convertedLexemes[term]?.[config];
      if (typeof raw !== 'string' || !/^\p{Script=Han}+$/u.test(raw)) throw Error('Invalid converted lexeme: ' + term);
      const correction = corrections.corrections[term]?.[config];
      if (correction && correction.expected !== raw) throw Error('OpenCC output changed; re-review the contextual correction: ' + term);
      const result = correction?.replacement || raw;
      if (!variants[term].includes(result)) variants[term].push(result);
    }
  }
  return Object.fromEntries(keys.map(key => [key, sources['zh-Hans'][key].map(source => source.replace(/\p{Script=Han}+/gu, term => variants[term].length === 1 ? variants[term][0] : '(?:' + variants[term].join('|') + ')'))]));
}

function runtimeSource(hant) {
  const all = Object.fromEntries(Object.entries({ ...sources, 'zh-Hant': hant }).sort(([a], [b]) => a.localeCompare(b, 'en')));
  return '// Generated by scripts/generate-core-intents.mjs. Edit locale sources and regenerate; no runtime conversion.\n' +
    'export const CORE_INTENT_PATTERNS_BY_LOCALE = ' + JSON.stringify(all, null, 2) + ' as const;\n';
}
function toolPath() {
  const command = process.env.OPENCC_BIN || 'opencc';
  const candidates = command.includes(path.sep) ? [path.resolve(command)] : (process.env.PATH || '').split(path.delimiter).map(dir => path.join(dir, command));
  for (const candidate of candidates) {
    try { fs.accessSync(candidate, fs.constants.X_OK); if (fs.statSync(candidate).isFile()) return fs.realpathSync(candidate); } catch {}
  }
  throw Error('Regeneration requires OpenCC ' + openccVersion + '; set OPENCC_BIN to its executable. Normal builds verify the checked-in artifact without OpenCC.');
}
function run(binary, args, input) {
  const result = spawnSync(binary, args, { input, encoding: 'utf8', timeout: 30000, maxBuffer: 1024 * 1024 });
  if (result.error) throw result.error;
  if (result.status !== 0) throw Error('OpenCC generation failed: ' + result.stderr.trim());
  return result.stdout;
}
function generate() {
  const binary = toolPath();
  if (!new RegExp('Version:\\s*' + openccVersion.replaceAll('.', '\\.') + '(?:\\s|$)').test(run(binary, ['--version']))) throw Error('Intent generation requires the pinned OpenCC ' + openccVersion);
  const data = path.resolve(binary, '../../share/opencc');
  const files = new Set(configurations);
  function dictionaries(value) {
    if (!value || typeof value !== 'object') return;
    if (typeof value.file === 'string') files.add(value.file);
    for (const item of Object.values(value)) dictionaries(item);
  }
  for (const name of configurations) dictionaries(JSON.parse(fs.readFileSync(path.join(data, name), 'utf8')));
  const dictionaryHashes = {};
  for (const name of [...files].sort()) {
    if (path.basename(name) !== name) throw Error('Unexpected OpenCC dictionary location');
    dictionaryHashes[name] = hash(fs.readFileSync(path.join(data, name)));
  }
  const convertedLexemes = Object.fromEntries(lexemes.map(term => [term, {}]));
  for (const config of configurations) {
    const lines = run(binary, ['-c', path.join(data, config)], lexemes.join('\n') + '\n').replace(/\r\n/g, '\n').replace(/\n$/, '').split('\n');
    if (lines.length !== lexemes.length) throw Error('OpenCC changed the lexeme record boundaries');
    lines.forEach((value, index) => { convertedLexemes[lexemes[index]][config] = value; });
  }
  const patterns = patternsFromLexemes(convertedLexemes);
  validatePatterns(patterns, 'zh-Hant');
  return { schemaVersion: 1, locale: 'zh-Hant', derivedFrom: 'zh-Hans', generator: 'OpenCC', openccVersion, configurations, sourceHashes, reviewedCorrectionsSha256, dictionaryHashes, convertedLexemes, patterns };
}
function verify(value) {
  if (value.schemaVersion !== 1 || value.locale !== 'zh-Hant' || value.derivedFrom !== 'zh-Hans' || value.generator !== 'OpenCC' || value.openccVersion !== openccVersion || JSON.stringify(value.configurations) !== JSON.stringify(configurations)) throw Error('Invalid generated intent provenance');
  if (JSON.stringify(value.sourceHashes) !== JSON.stringify(sourceHashes)) throw Error('Intent source changed: run npm run generate:core-intents and review the generated variants');
  const expectedDictionaries = ['STCharacters.ocd2', 'STPhrases.ocd2', 'TWPhrases.ocd2', 'TWVariants.ocd2', ...configurations].sort();
  if (!value.dictionaryHashes || JSON.stringify(Object.keys(value.dictionaryHashes).sort()) !== JSON.stringify(expectedDictionaries) || Object.values(value.dictionaryHashes).some(digest => !/^[a-f0-9]{64}$/.test(digest))) throw Error('Missing OpenCC dictionary provenance');
  if (value.reviewedCorrectionsSha256 !== reviewedCorrectionsSha256 || JSON.stringify(value.patterns) !== JSON.stringify(patternsFromLexemes(value.convertedLexemes))) throw Error('Reviewed intent variants changed: regenerate the artifacts');
  validatePatterns(value.patterns, 'zh-Hant');
  if (fs.readFileSync(generatedTs, 'utf8') !== runtimeSource(value.patterns)) throw Error('Runtime intent artifact is stale; regenerate it');
}
if (mode === '--verify') {
  verify(JSON.parse(fs.readFileSync(generatedJson, 'utf8')));
  console.error('Intent sources and generated runtime artifact are consistent (no converter needed).');
} else {
  const value = generate(), output = json(value), runtime = runtimeSource(value.patterns);
  if (mode === '--generate') {
    fs.mkdirSync(path.dirname(generatedJson), { recursive: true });
    fs.writeFileSync(generatedJson, output);
    fs.writeFileSync(generatedTs, runtime);
  } else {
    if (fs.readFileSync(generatedJson, 'utf8') !== output || fs.readFileSync(generatedTs, 'utf8') !== runtime) throw Error('OpenCC regeneration differs from the checked-in artifacts');
  }
  console.error('OpenCC ' + openccVersion + ' ' + configurations.join(' + ') + ': ' + keys.length + ' intent categories ' + (mode === '--generate' ? 'generated' : 'reproduced') + '.');
}
